  function getLang() {
    return currentLang;
  }

  function t(key, vars = {}) {
    const dict = MESSAGES[currentLang] || MESSAGES.ja;
    let str = dict[key];
    if (str === undefined) str = MESSAGES.ja[key];
    if (str === undefined) return key;
    Object.keys(vars).forEach(k => {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
    });
    return str;
  }

  function shapeName(id, fallback) {
    if (currentLang === "en") {
      if (id === "math_plot") return t("shape.math_plot");
      if (id === "frame") return t("shape.frame");
      return SHAPE_NAMES_EN[id] || fallback || id;
    }
    return fallback || (id === "math_plot" ? t("shape.math_plot") : (id === "frame" ? t("shape.frame") : id));
  }

  function warpName(id, fallback) {
    const map = WARP_NAMES[currentLang] || WARP_NAMES.ja;
    return map[id] || fallback || id;
  }

  function presetName(id, fallback) {
    if (currentLang === "en") {
      return MATH_PRESET_NAMES_EN[id] || fallback || id;
    }
    return fallback || id;
  }

  function applyDomTranslations(root = document) {
    document.documentElement.lang = currentLang;
    document.title = t("app.title");

    root.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    });
    root.querySelectorAll("[data-i18n-title]").forEach(el => {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.setAttribute("title", t(key));
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key));
    });
  }

  function setLang(lang) {
    const next = lang === "en" ? "en" : "ja";
    if (next === currentLang) return;
    currentLang = next;
    try {
      localStorage.setItem(STORAGE_KEY, currentLang);
    } catch (e) {
      // ignore
    }
    applyDomTranslations(document);
    listeners.forEach(fn => {
      try { fn(currentLang); } catch (e) { /* ignore */ }
    });
  }

  function toggleLang() {
    setLang(currentLang === "ja" ? "en" : "ja");
  }

  function onChange(fn) {
    if (typeof fn === "function") listeners.push(fn);
  }

  return {
    getLang,
    setLang,
    toggleLang,
    t,
    shapeName,
    warpName,
    presetName,
    applyDomTranslations,
    onChange
  };
